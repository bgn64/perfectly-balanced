import { spawnSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

function run(command, args) {
  const result = spawnSync(command, args, {
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  })

  if (result.stdout) {
    process.stdout.write(result.stdout)
  }
  if (result.stderr) {
    process.stderr.write(result.stderr)
  }

  if (result.error || result.status !== 0) {
    throw result.error ?? new Error(`${command} exited with ${result.status}.`)
  }

  return result.stdout
}

function runSupabase(args) {
  if (process.platform !== 'win32') {
    return run('supabase', args)
  }

  const command = ['supabase', ...args]
    .map((argument) =>
      /[\s"]/u.test(argument)
        ? `"${argument.replaceAll('"', '\\"')}"`
        : argument,
    )
    .join(' ')

  return run(process.env.ComSpec ?? 'cmd.exe', ['/d', '/s', '/c', command])
}

function parseEnvironment(output) {
  const values = new Map()

  for (const line of output.split(/\r?\n/u)) {
    const separator = line.indexOf('=')
    if (separator === -1) {
      continue
    }
    const key = line.slice(0, separator).trim()
    const rawValue = line.slice(separator + 1).trim()
    const value =
      rawValue.startsWith('"') && rawValue.endsWith('"')
        ? JSON.parse(rawValue)
        : rawValue
    values.set(key, value)
  }

  return values
}

try {
  run(process.platform === 'win32' ? 'docker.exe' : 'docker', [
    'info',
    '--format',
    '{{.ServerVersion}}',
  ])
} catch {
  throw new Error(
    'Docker Desktop must be installed and running before local development can start.',
  )
}

runSupabase(['start'])
const environment = parseEnvironment(runSupabase(['status', '--output', 'env']))
const apiUrl = environment.get('API_URL')
const anonKey = environment.get('ANON_KEY')

if (!apiUrl || !anonKey) {
  throw new Error(
    'Supabase did not provide the local API URL and anonymous key.',
  )
}

const localEnvironment = [
  '# Generated by scripts/bootstrap-local-supabase.mjs. Do not edit.',
  `VITE_APP_NAME=${JSON.stringify('Perfectly Balanced')}`,
  `VITE_SUPABASE_URL=${JSON.stringify(apiUrl)}`,
  `VITE_SUPABASE_ANON_KEY=${JSON.stringify(anonKey)}`,
  `VITE_SITE_URL=${JSON.stringify('http://localhost:5173')}`,
  'VITE_LOCAL_DEMO_MODE=true',
  `VITE_LOCAL_TEST_EMAIL=${JSON.stringify('dev@example.test')}`,
  `VITE_LOCAL_TEST_PASSWORD=${JSON.stringify('local-dev-password')}`,
  '',
].join('\n')

writeFileSync(resolve('.env.development.local'), localEnvironment, 'utf8')
console.log(
  'Local Supabase is ready and .env.development.local has been generated.',
)
